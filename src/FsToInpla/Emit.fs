module FsToInpla.Emit

open FsToInpla.Net
open FsToInpla.NetGen

exception LinearityError of string

/// Renders the program as an Inpla source file.
let render (o: Output) : string =
    let errors = (o.Rules |> List.collect checkRule) @ checkNet o.Net [ root ]
    if not errors.IsEmpty then raise (LinearityError (String.concat "\n" errors))
    let sb = System.Text.StringBuilder()
    let line (s: string) = sb.AppendLine s |> ignore
    line "// Generated by fs2inpla."
    line ""
    line "// ---- Rules"
    for r in o.Rules do line (printRule r)
    line ""
    line "// ---- Net"
    for eq in o.Net do line (printEq eq + ";")
    line ""
    line (root + ";")
    sb.ToString()
